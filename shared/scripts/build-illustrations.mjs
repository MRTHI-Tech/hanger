/**
 * The photo-guidance illustrations, turned into React components.
 *
 * The drawings in ../assets/illustrations are the source of truth — that is
 * where a redraw lands, and it should not have to be pasted into a .tsx by
 * hand. This reads them and writes src/illustrations/pose.tsx, so exporting
 * new art from a design tool and re-running this is the whole update.
 *
 * Two things change on the way through:
 *
 *   the fill      #000000 becomes currentColor, so one drawing works on a
 *                 muted card, in a warning, and in whatever the phone does
 *                 with it later. Hard-coded black would be a second asset the
 *                 first time anything sits on a dark surface.
 *   the size      width/height are dropped. They are 1024 square in the file
 *                 and every use so far wants "fill the box you're in"; the
 *                 viewBox keeps the proportions either way.
 *
 * Run: npm run build:illustrations --workspace shared
 */
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, '..', 'assets', 'illustrations');
const out = join(here, '..', 'src', 'illustrations', 'pose.tsx');

/** `03-cropped-too-short.svg` -> `CroppedTooShort`. */
function componentName(file) {
  return file
    .replace(/\.svg$/, '')
    .replace(/^\d+-/, '')
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function extract(svg, file) {
  const path = /<path\b[^>]*\bd="([^"]+)"/.exec(svg);
  if (!path) throw new Error(`${file}: no <path d="..."> found`);

  const viewBox = /\bviewBox="([^"]+)"/.exec(svg);
  if (!viewBox) throw new Error(`${file}: no viewBox`);

  // The author's own words, kept rather than reinvented — they describe the
  // drawing better than a filename does.
  const label = /\baria-label="([^"]+)"/.exec(svg);

  return {
    d: path[1].trim(),
    viewBox: viewBox[1],
    label: label ? label[1] : componentName(file),
  };
}

const files = readdirSync(assets)
  .filter((f) => f.endsWith('.svg'))
  .sort();

if (files.length === 0) throw new Error(`no .svg files in ${assets}`);

const drawings = files.map((file) => ({
  file,
  name: componentName(file),
  ...extract(readFileSync(join(assets, file), 'utf8'), file),
}));

const viewBoxes = new Set(drawings.map((d) => d.viewBox));
if (viewBoxes.size > 1) {
  // They are laid out in a row at matching sizes, so a stray viewBox would
  // show up as one figure mysteriously larger than its neighbours.
  throw new Error(`illustrations disagree on viewBox: ${[...viewBoxes].join(', ')}`);
}

const body = `/**
 * Photo-guidance illustrations.
 *
 * GENERATED by shared/scripts/build-illustrations.mjs — do not edit.
 * The drawings live in shared/assets/illustrations; change them there and run
 * \`npm run build:illustrations --workspace shared\`.
 *
 * Drawn in currentColor, so the surface decides the ink.
 */
import type {SVGProps} from 'react';

export interface IllustrationProps
  extends Omit<SVGProps<SVGSVGElement>, 'children' | 'viewBox'> {
  /**
   * An accessible name. Omit it where the drawing sits next to a caption that
   * already says the same thing — which is every use today — and it is marked
   * decorative instead of read out twice.
   */
  title?: string;
}

function Illustration({
  d,
  title,
  ...rest
}: IllustrationProps & {d: string}) {
  return (
    <svg
      viewBox="${drawings[0].viewBox}"
      width="100%"
      height="100%"
      {...(title ? {role: 'img', 'aria-label': title} : {'aria-hidden': true})}
      {...rest}>
      <path d={d} fill="currentColor" fillRule="evenodd" clipRule="evenodd" />
    </svg>
  );
}

${drawings
  .map(({name, d, label, file}) => {
    const constant = `${name.replace(/(?<!^)([A-Z])/g, '_$1').toUpperCase()}_D`;
    return `/** ${label}. From \`${file}\`. */
const ${constant} =
  '${d}';

export function ${name}(props: IllustrationProps) {
  return <Illustration d={${constant}} {...props} />;
}`;
  })
  .join('\n\n')}
`;

writeFileSync(out, body);
console.log(
  `wrote ${out.split('/').slice(-3).join('/')} — ${drawings
    .map((d) => d.name)
    .join(', ')}`,
);
