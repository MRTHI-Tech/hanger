/**
 * The guidance illustrations, turned into React components.
 *
 * The drawings in ../assets/illustrations are the source of truth — that is
 * where a redraw lands, and it should not have to be pasted into a .tsx by
 * hand. This reads them and writes one module per set, so exporting new art
 * from a design tool and re-running this is the whole update.
 *
 * A set is a subdirectory: `pose/` becomes src/illustrations/pose.tsx,
 * `garment/` becomes garment.tsx. They are separate because they are cropped
 * differently — the pose drawings are tall and the garment ones are wide — and
 * because a guide should be able to gain a drawing without the other one
 * silently gaining it too.
 *
 * Two things change on the way through:
 *
 *   the fill      #000000 becomes currentColor, so one drawing works on a
 *                 muted card, in a warning, and in whatever the phone does
 *                 with it later. Hard-coded black would be a second asset the
 *                 first time anything sits on a dark surface.
 *   the size      width/height are dropped. They are 1024 square in the file
 *                 and every use so far wants "fill the box you're in"; the
 *                 viewBox keeps the proportions either way.
 *
 * Run: npm run build:illustrations --workspace shared
 */
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, '..', 'assets', 'illustrations');
const outDir = join(here, '..', 'src', 'illustrations');

/** `03-cropped-too-short.svg` -> `CroppedTooShort`. */
function componentName(file) {
  return file
    .replace(/\.svg$/, '')
    .replace(/^\d+-/, '')
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function extract(svg, file) {
  const path = /<path\b[^>]*\bd="([^"]+)"/.exec(svg);
  if (!path) throw new Error(`${file}: no <path d="..."> found`);

  const viewBox = /\bviewBox="([^"]+)"/.exec(svg);
  if (!viewBox) throw new Error(`${file}: no viewBox`);

  // The author's own words, kept rather than reinvented — they describe the
  // drawing better than a filename does.
  const label = /\baria-label="([^"]+)"/.exec(svg);

  return {
    d: path[1].trim(),
    viewBox: viewBox[1],
    label: label ? label[1] : componentName(file),
  };
}

function buildSet(set) {
  const dir = join(assets, set);
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.svg'))
    .sort();

  if (files.length === 0) throw new Error(`no .svg files in ${dir}`);

  const drawings = files.map((file) => ({
    file,
    name: componentName(file),
    ...extract(readFileSync(join(dir, file), 'utf8'), file),
  }));

  const viewBoxes = new Set(drawings.map((d) => d.viewBox));
  if (viewBoxes.size > 1) {
    // They are laid out in a row at matching sizes, so a stray viewBox would
    // show up as one figure mysteriously larger than its neighbours.
    throw new Error(
      `${set}: illustrations disagree on viewBox: ${[...viewBoxes].join(', ')}`,
    );
  }

  const body = `/**
 * Guidance illustrations — the \`${set}\` set.
 *
 * GENERATED by shared/scripts/build-illustrations.mjs — do not edit.
 * The drawings live in shared/assets/illustrations/${set}; change them there and
 * run \`npm run build:illustrations --workspace shared\`.
 *
 * Drawn in currentColor, so the surface decides the ink.
 */
import {Illustration, type IllustrationProps} from './base';

const VIEW_BOX = '${drawings[0].viewBox}';

${drawings
  .map(({name, d, label, file}) => {
    const constant = `${name.replace(/(?<!^)([A-Z])/g, '_$1').toUpperCase()}_D`;
    return `/** ${label}. From \`${file}\`. */
const ${constant} =
  '${d}';

export function ${name}(props: IllustrationProps) {
  return <Illustration d={${constant}} viewBox={VIEW_BOX} {...props} />;
}`;
  })
  .join('\n\n')}
`;

  writeFileSync(join(outDir, `${set}.tsx`), body);
  return drawings.map((d) => d.name);
}

const sets = readdirSync(assets, {withFileTypes: true})
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

if (sets.length === 0) {
  throw new Error(`no illustration sets (subdirectories) in ${assets}`);
}

for (const set of sets) {
  console.log(`wrote src/illustrations/${set}.tsx — ${buildSet(set).join(', ')}`);
}

// One import path for both sets, so a guide asks for a drawing by name and
// doesn't have to know which folder it came out of.
writeFileSync(
  join(outDir, 'index.ts'),
  `/**
 * Every guidance illustration.
 *
 * GENERATED by shared/scripts/build-illustrations.mjs — do not edit.
 */
export {type IllustrationProps} from './base';
${sets.map((set) => `export * from './${set}';`).join('\n')}
`,
);
console.log(`wrote src/illustrations/index.ts — ${sets.join(', ')}`);
